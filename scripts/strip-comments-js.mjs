#!/usr/bin/env node
// strip-comments-js.mjs — AST-based comment stripper for TS/TSX/JS/JSX.
//
// Uses the TypeScript compiler API (ts.createSourceFile) for tokenization
// (handles regex literals, template literals, JSX correctly) and magic-string
// for surgical edits.
//
// PRESERVED (never stripped):
//   - JSDoc blocks (any /** ... */)
//   - Triple-slash directives (/// <reference ... />)
//   - Single-line pragmas: @ts-expect-error, @ts-ignore, @ts-nocheck,
//     eslint-disable[-line|-next-line], eslint-enable, prettier-ignore,
//     biome-ignore, react-refresh, @vite-ignore, @preserve, @license,
//     @__PURE__, webpack, @jsxImportSource, @jsxRuntime
//   - Block-comment pragmas: /* eslint-disable */, /* eslint-enable */,
//     /* @preserve */, /* @license */, /* @__PURE__ */, /* webpack ... */,
//     /* @vite-ignore */, /* @jsxImportSource */, /* @jsxRuntime */
//
// STRIPPED: every other // line comment, /* */ block comment, and
// {/* ... */} JSX comment expression.
//
// Usage:
//   node scripts/strip-comments-js.mjs --root <dir> [--dry]
//   node scripts/strip-comments-js.mjs [--dry] file1.ts file2.tsx ...
//
// Run from repo root OR from frontend/ — the script resolves typescript +
// magic-string from `frontend/node_modules` either way.

import { promises as fs, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const feNodeModules = path.join(repoRoot, 'frontend', 'node_modules');

const tsEntry = path.join(feNodeModules, 'typescript', 'lib', 'typescript.js');
const msEntry = path.join(feNodeModules, 'magic-string', 'dist', 'magic-string.es.mjs');

if (!existsSync(tsEntry)) {
  console.error(`STRIP_JS_SETUP_ERROR: typescript not found at ${tsEntry} — run \`npm install\` in frontend/.`);
  process.exit(2);
}
if (!existsSync(msEntry)) {
  console.error(`STRIP_JS_SETUP_ERROR: magic-string not found at ${msEntry} — run \`npm install\` in frontend/.`);
  process.exit(2);
}

const tsMod = await import(pathToFileURL(tsEntry).href);
const ts = tsMod.default ?? tsMod;
const msMod = await import(pathToFileURL(msEntry).href);
const MagicString = msMod.default ?? msMod;

// ---- argv ----------------------------------------------------------------

const argv = process.argv.slice(2);
let dryRun = false;
let rootDir = '';
const explicitFiles = [];
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === '--dry') dryRun = true;
  else if (a === '--root') rootDir = argv[++i];
  else explicitFiles.push(a);
}

// ---- skip rules ----------------------------------------------------------

const skipPathSubstrings = [
  `${path.sep}node_modules${path.sep}`,
  `${path.sep}dist${path.sep}`,
  `${path.sep}.planning${path.sep}`,
  `${path.sep}backend${path.sep}internal${path.sep}static${path.sep}dist${path.sep}`,
];

const skipSuffixes = [
  '.min.js',
  '.gen.go',
  '.generated.ts',
  '.generated.tsx',
];

const skipBasenames = new Set([
  'schema.d.ts',
  'schema.gen.d.ts',
]);

const extToKind = {
  '.ts': () => ts.ScriptKind.TS,
  '.tsx': () => ts.ScriptKind.TSX,
  '.js': () => ts.ScriptKind.JS,
  '.jsx': () => ts.ScriptKind.JSX,
  '.mjs': () => ts.ScriptKind.JS,
  '.cjs': () => ts.ScriptKind.JS,
};

function shouldSkip(p) {
  for (const sub of skipPathSubstrings) if (p.includes(sub)) return true;
  for (const suf of skipSuffixes) if (p.endsWith(suf)) return true;
  if (skipBasenames.has(path.basename(p))) return true;
  // First 4 KiB scan for generated marker.
  try {
    const buf = readFileSync(p);
    const head = buf.subarray(0, Math.min(buf.length, 4096)).toString('utf8');
    if (head.includes('Code generated by ') || /AUTOGENERATED/i.test(head)) return true;
  } catch {
    return true;
  }
  return false;
}

// ---- preserve classifiers -----------------------------------------------

const singleLinePragmaPrefixes = [
  '@ts-expect-error',
  '@ts-ignore',
  '@ts-nocheck',
  'eslint-disable',
  'eslint-enable',
  'prettier-ignore',
  'biome-ignore',
  'react-refresh',
  '@vite-ignore',
  '@preserve',
  '@license',
  '@__PURE__',
  'webpack',
  '@jsxImportSource',
  '@jsxRuntime',
  // Test framework env directives:
  '@vitest-environment',
  '@jest-environment',
];

const blockPragmaPrefixes = [
  'eslint-disable',
  'eslint-enable',
  '@preserve',
  '@license',
  '@__PURE__',
  'webpack',
  '@vite-ignore',
  '@jsxImportSource',
  '@jsxRuntime',
];

function isPreservedLineComment(text) {
  // text includes the leading "//"
  if (text.startsWith('///')) return true; // triple-slash directive
  // Strip "//" and any leading whitespace.
  const inner = text.replace(/^\/\/\s*/, '').trimStart();
  for (const pre of singleLinePragmaPrefixes) {
    if (inner.startsWith(pre)) return true;
  }
  return false;
}

function isPreservedBlockComment(text) {
  // text includes the leading "/*" and trailing "*/"
  if (text.startsWith('/**')) {
    // JSDoc — preserve, unless it's actually "/**/" (zero-content) which
    // serves no purpose. /**/ is harmless to strip but harmless to keep;
    // keep to err on the side of not touching anything that LOOKS like jsdoc.
    return true;
  }
  // Strip "/*" and "*/" and look at inner trimmed.
  const inner = text.slice(2, -2).trim();
  for (const pre of blockPragmaPrefixes) {
    if (inner.startsWith(pre)) return true;
  }
  return false;
}

// ---- core ----------------------------------------------------------------

const stats = {
  scanned: 0,
  modified: 0,
  removed: 0,
  preserved: 0,
  parseFailures: 0,
};

async function walk(dir) {
  const out = [];
  async function recurse(d) {
    let entries;
    try {
      entries = await fs.readdir(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) {
        if (e.name === 'node_modules' || e.name === 'dist' || e.name === '.git' || e.name === '.planning') continue;
        await recurse(p);
      } else if (e.isFile()) {
        const ext = path.extname(e.name);
        if (extToKind[ext]) out.push(p);
      }
    }
  }
  await recurse(dir);
  return out;
}

function classifyRange(source, range) {
  const text = source.slice(range.pos, range.end);
  if (range.kind === ts.SyntaxKind.SingleLineCommentTrivia) {
    return isPreservedLineComment(text) ? 'preserve' : 'strip';
  }
  if (range.kind === ts.SyntaxKind.MultiLineCommentTrivia) {
    return isPreservedBlockComment(text) ? 'preserve' : 'strip';
  }
  return 'preserve';
}

// Collect every comment range in the file by scanning all node positions.
// We dedupe by (pos,end).
function collectComments(sf, source) {
  const seen = new Set();
  const ranges = [];
  function add(r) {
    if (!r) return;
    for (const item of r) {
      const key = `${item.pos}:${item.end}`;
      if (seen.has(key)) continue;
      seen.add(key);
      ranges.push(item);
    }
  }
  function visit(node) {
    add(ts.getLeadingCommentRanges(source, node.pos));
    add(ts.getTrailingCommentRanges(source, node.end));
    ts.forEachChild(node, visit);
  }
  visit(sf);
  // Also catch trailing comments at end of file.
  add(ts.getLeadingCommentRanges(source, sf.endOfFileToken.pos));
  return ranges;
}

// Detect JSX comment expressions: {/* ... */}. The TS AST models these as
// JsxExpression nodes whose expression is undefined; the comment lives in
// the trivia between { and }. We want to remove the whole {...} span when
// the inner comment is strip-only.
function collectJsxCommentSpans(sf, source) {
  const spans = [];
  function visit(node) {
    if (node.kind === ts.SyntaxKind.JsxExpression && node.expression === undefined) {
      // Find leading comments inside the { ... } — these are between
      // node.pos (which includes leading trivia outside) and node.end.
      // The actual { token starts at the first non-trivia byte.
      // For our purposes, we treat the whole JsxExpression span as a unit:
      // if every comment inside is strip-eligible, remove [openBrace..closeBrace+1].
      const start = node.getStart(sf);
      const end = node.getEnd();
      // Look up the comments inside.
      // Use the source text between { and }:
      const inner = source.slice(start + 1, end - 1);
      // Quick check: contains a comment?
      if (!/\/\*|\/\//.test(inner)) return;
      spans.push({ start, end, inner });
    }
    ts.forEachChild(node, visit);
  }
  visit(sf);
  return spans;
}

async function processFile(p) {
  stats.scanned++;
  const ext = path.extname(p);
  const kindFn = extToKind[ext];
  if (!kindFn) return;
  let source;
  try {
    source = await fs.readFile(p, 'utf8');
  } catch (e) {
    console.error(`STRIP_JS_READ_ERROR: ${p}: ${e.message}`);
    stats.parseFailures++;
    return;
  }
  const sf = ts.createSourceFile(p, source, ts.ScriptTarget.Latest, true, kindFn());
  const diags = sf.parseDiagnostics || [];
  const errorDiags = diags.filter((d) => d.category === ts.DiagnosticCategory.Error);
  if (errorDiags.length > 0) {
    const first = errorDiags[0];
    const msg = ts.flattenDiagnosticMessageText(first.messageText, '\n');
    console.error(`STRIP_JS_PARSE_ERROR: ${p}: ${msg}`);
    stats.parseFailures++;
    return;
  }

  const ranges = collectComments(sf, source);
  const jsxSpans = collectJsxCommentSpans(sf, source);
  const ms = new MagicString(source);

  // Track which (pos,end) byte ranges we've already removed so we don't
  // double-remove a JSX-wrapped comment.
  const removedByPos = new Set();

  // First, process JSX comment expressions: strip {...} if ALL comments
  // inside are non-preserved.
  for (const span of jsxSpans) {
    // Gather comment ranges within [span.start+1, span.end-1].
    const inside = ranges.filter((r) => r.pos >= span.start && r.end <= span.end);
    if (inside.length === 0) continue;
    const allStrip = inside.every((r) => classifyRange(source, r) === 'strip');
    if (!allStrip) {
      // Preserve the whole expression as-is.
      for (const r of inside) removedByPos.add(`${r.pos}:${r.end}`); // mark so plain pass skips
      continue;
    }
    ms.remove(span.start, span.end);
    for (const r of inside) removedByPos.add(`${r.pos}:${r.end}`);
  }

  // Then process plain comments.
  for (const r of ranges) {
    const key = `${r.pos}:${r.end}`;
    if (removedByPos.has(key)) continue;
    const verdict = classifyRange(source, r);
    if (verdict === 'preserve') {
      stats.preserved++;
      continue;
    }
    // For single-line comments, also consume the trailing newline if it
    // immediately follows — keeps line count clean.
    let end = r.end;
    if (r.kind === ts.SyntaxKind.SingleLineCommentTrivia) {
      // Find the start of the line (look back to previous newline) — if the
      // comment is the only content on the line, remove the whole line
      // including its leading whitespace and trailing newline.
      let lineStart = r.pos;
      while (lineStart > 0 && source[lineStart - 1] !== '\n') {
        const ch = source[lineStart - 1];
        if (ch !== ' ' && ch !== '\t') {
          // Mixed-content line (e.g. `code; // note`); keep code, drop comment.
          lineStart = r.pos;
          break;
        }
        lineStart--;
      }
      if (lineStart < r.pos) {
        // Whole-line comment: also drop the trailing newline if present.
        if (source[end] === '\r') end++;
        if (source[end] === '\n') end++;
        ms.remove(lineStart, end);
      } else {
        // Trailing inline: drop comment, preserve trailing whitespace before newline.
        // Also drop any whitespace immediately preceding the comment that was inserted as separation.
        let start = r.pos;
        while (start > 0 && (source[start - 1] === ' ' || source[start - 1] === '\t')) start--;
        ms.remove(start, end);
      }
    } else {
      // Multi-line /* */ comment.
      // If on its own line, remove the entire line.
      let lineStart = r.pos;
      while (lineStart > 0 && source[lineStart - 1] !== '\n') {
        const ch = source[lineStart - 1];
        if (ch !== ' ' && ch !== '\t') {
          lineStart = r.pos;
          break;
        }
        lineStart--;
      }
      let lineEnd = r.end;
      // Check if rest of line is whitespace only.
      let afterIsBlank = true;
      while (lineEnd < source.length && source[lineEnd] !== '\n') {
        const ch = source[lineEnd];
        if (ch !== ' ' && ch !== '\t' && ch !== '\r') {
          afterIsBlank = false;
          break;
        }
        lineEnd++;
      }
      if (lineStart < r.pos && afterIsBlank) {
        if (source[lineEnd] === '\n') lineEnd++;
        ms.remove(lineStart, lineEnd);
      } else {
        // Inline block — just strip the comment plus a single leading/trailing space if redundant.
        let start = r.pos;
        let endTrim = r.end;
        if (source[endTrim] === ' ') endTrim++;
        else if (start > 0 && source[start - 1] === ' ') start--;
        ms.remove(start, endTrim);
      }
    }
    stats.removed++;
  }

  let out = ms.toString();
  // Collapse 3+ blank lines to 2 blank lines (3 newlines).
  out = out.replace(/\n{4,}/g, '\n\n\n');

  if (out === source) return;
  stats.modified++;
  if (dryRun) return;
  const tmp = p + '.strip.tmp';
  await fs.writeFile(tmp, out, 'utf8');
  await fs.rename(tmp, p);
}

// ---- main ----------------------------------------------------------------

const files = [];
if (rootDir) {
  const root = path.resolve(rootDir);
  const walked = await walk(root);
  for (const f of walked) if (!shouldSkip(f)) files.push(f);
}
for (const f of explicitFiles) {
  const abs = path.resolve(f);
  if (!shouldSkip(abs)) files.push(abs);
}

for (const f of files) {
  await processFile(f);
}

console.error(
  `strip-comments-js: scanned=${stats.scanned} modified=${stats.modified} removed=${stats.removed} preserved=${stats.preserved} parse_failures=${stats.parseFailures} dry=${dryRun}`,
);
if (stats.parseFailures > 0) process.exit(2);
